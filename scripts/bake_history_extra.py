# —— HTML 解析辅助 ——
_TAG_RE = re.compile(r"<[^>]+>")


def html_to_text(s: str) -> str:
    """去除百度百科返回的 HTML 标签与实体编码，返回纯文本。"""
    if not s:
        return ""
    s = _TAG_RE.sub("", s)
    s = unescape(s)
    return s.strip()


