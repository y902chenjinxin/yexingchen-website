def is_cn_main(text: str) -> bool:
    """判断文本主体是否为中国相关。
    规则（宁杀错不放过）：
      1. 含【非中国主体词】且不含【强中国词】 → 剔除
      2. 含【中国主体关键词】 → 保留
    """
    if not text:
        return False
    if any(k in text for k in _FOREIGN_KILL) and not any(k in text for k in _STRONG_CN_KEEP):
        return False
    return bool(CN_RE.search(text))


def fetch_month(m: int) -> dict[str, list]:
    """下载单月 JSON：形如 {MM: {MMDD: [events...]}}"""
    url = BAIDU.format(m=m)
    try:
        req = urllib.request.Request(url, headers={"User-Agent": UA, "Referer": "https://baike.baidu.com/calendar"})
        with urllib.request.urlopen(req, timeout=20) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except Exception as e:  # noqa: BLE001
        print(f"  ! month {m:02d} fetch failed: {e}", file=sys.stderr)
        return {}

    raw = data.get(f"{m:02d}") or {}
    out: dict[str, list] = {}
    for k, items in raw.items():
        # k 形如 "0101" / "0102" ... / "0229"
        if not isinstance(items, list):
            continue
        cleaned = []
        for ev in items:
            title = html_to_text(ev.get("title") or "")
            desc = html_to_text(ev.get("desc") or "")
            year = ev.get("year") or 0
            if not title:
                continue
            # 主体判定：仅当 title 命中【中国主体关键词】才视为中国相关。
            # 这样避免 desc 里"顺带提到中国"的非中国主体被误收录。
            if not is_cn_main(title):
                continue
            cleaned.append({
                "year": int(year) if year else 0,
                "title": title,
                "desc": desc,
            })
        # 按年份倒序去重（同 title 合并）
        seen = set()
        uniq = []
        for c in cleaned:
            kk = (c["year"], c["title"])
            if kk in seen:
                continue
            seen.add(kk)
            uniq.append(c)
        uniq.sort(key=lambda x: -(int(x.get("year") or 0)))
        # 限制单日条数：保留前 MAX_PER_DATE 条（多数日期条目少，全保留）
        out[k] = uniq[:MAX_PER_DATE]
    return out


def main():
    result: dict[str, list] = {}
    with ThreadPoolExecutor(max_workers=THREADS) as pool:
        futs = {pool.submit(fetch_month, m): m for m in range(1, 13)}
        for fut in as_completed(futs):
            m = futs[fut]
            month_data = fut.result()
            for k, v in month_data.items():
                if v:
                    result.setdefault(k, []).extend(v)
            print(f"  month {m:02d} done")
    # 最终去重 + 单日上限
    final: dict[str, list] = {}
    for k, items in result.items():
        seen = set()
        uniq = []
        for it in items:
            kk = (it["year"], it["title"])
            if kk in seen:
                continue
            seen.add(kk)
            uniq.append(it)
        uniq.sort(key=lambda x: -(int(x.get("year") or 0)))
        final[k] = uniq[:MAX_PER_DATE]

    # 全年键补齐（按月日）保证 366 键都存在
    for m in range(1, 13):
        ndays = calendar.monthrange(2000, m)[1]
        for d in range(1, ndays + 1):
            final.setdefault(f"{m:02d}{d:02d}", [])

    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(final, f, ensure_ascii=False, separators=(",", ":"))
    nonempty = sum(1 for v in final.values() if v)
    total = sum(len(v) for v in final.values())
    print(f"cover {nonempty}/366 dates, {total} events -> {OUT}")


if __name__ == "__main__":
    main()